// ─── Approved leadership memorandum ──────────────────────────────────────────
// This file is the ONLY place the home-page memorandum is defined. The page never
// invents wording: every string below must be copied exactly from the approved,
// signed source document supplied by the product owner.
//
// STATUS: no approved memorandum has been supplied yet, so APPROVED_MEMO is null and
// the home page renders only the hero. To publish it, follow docs/MEMO_INTAKE.md,
// fill in `APPROVED_MEMO`, and run `npm run test:unit` (it validates the memo).
//
// Layout reference: AFH 33-337, The Tongue and Quill, Chapter 14, "The Memorandum for
// Record: Separate Page" (pp. 190-191, 27 May 2015 edition). Confirm the current
// edition and any command or local guidance before calling the result compliant.

export interface MemoBlock {
  // The paragraph label exactly as it appears in the source ("1.", "a.", "(1)").
  // Stored as text, not generated by CSS counters, so it can never drift from the source.
  label?: string;
  // 0 = numbered paragraph, 1 = subparagraph, 2 = sub-subparagraph (AFH 33-337 indents each level).
  level: 0 | 1 | 2;
  text: string;
}

export interface SignatureArtwork {
  viewBox: string;
  // Faithful filled outline(s) of the authorized signature artwork (SVG path data).
  outline: string[];
  // Optional centerline path(s) that follow the pen. They drive the draw-on mask only and are
  // never painted. Without them the signature is revealed with a left-to-right wipe.
  pen?: string[];
  penWidth?: number;
  alt: string;
  // Provenance of the artwork that was converted. The source file is kept in the repo.
  source: {
    file: string;
    sha256: string;
    description: string;
  };
}

export interface ApprovedMemo {
  // The exact title line of the signed source ("MEMORANDUM FOR RECORD" for a separate-page MFR).
  // If the source is a different document type, use its own title and set `addressees`;
  // do not relabel it as an MFR.
  heading: string;
  isSeparatePageMfr: boolean;
  // Approved organizational letterhead, line by line. `sealUrl` only if an approved seal asset is supplied.
  letterhead: { lines: string[]; sealUrl?: string; sealAlt?: string };
  date: { iso: string; label: string };
  // Required for any non-MFR template; a separate-page MFR omits both FROM and addressees.
  addressees?: string[];
  from?: string;
  subject: string;
  reference?: string;
  body: MemoBlock[];
  signature: SignatureArtwork;
  // Signature block lines exactly as printed under the signature.
  signatureBlock: string[];
  // The exact approved endorsement attribution, as supported by the memorandum.
  endorsement: string;
  provenance: {
    title: string;
    sourceUrl?: string;
    localUrl?: string;
    sha256: string;
    approvedBy: string;
  };
}

export const APPROVED_MEMO: ApprovedMemo | null = null;

export function memoProblems(memo: ApprovedMemo | null): string[] {
  if (!memo) return [];
  const problems: string[] = [];
  const need = (ok: unknown, message: string) => { if (!ok) problems.push(message); };
  need(memo.heading.trim(), "heading is empty");
  need(memo.letterhead.lines.length > 0, "approved letterhead lines are missing");
  need(/^\d{4}-\d{2}-\d{2}$/.test(memo.date.iso) && memo.date.label.trim(), "date is incomplete");
  need(memo.subject.trim(), "subject is empty");
  need(memo.body.length > 0 && memo.body.every((block) => block.text.trim()), "memo body is empty or has blank paragraphs");
  need(memo.signature.outline.length > 0 && memo.signature.viewBox, "signature SVG artwork is missing");
  need(memo.signature.alt.trim(), "signature alt text is missing");
  need(/^[0-9a-f]{64}$/.test(memo.signature.source.sha256), "signature source SHA-256 is missing");
  need(memo.signatureBlock.length > 0, "signature block is missing");
  need(memo.endorsement.trim(), "approved endorsement attribution is missing");
  need(/^[0-9a-f]{64}$/.test(memo.provenance.sha256), "memo source SHA-256 is missing");
  need(memo.provenance.approvedBy.trim(), "approval record is missing");
  if (memo.isSeparatePageMfr) {
    need(!memo.from, "a separate-page MFR must not have a FROM line");
    need(!memo.addressees?.length, "a separate-page MFR has no addressees; use the source's own template instead");
  } else {
    need(memo.addressees?.length, "non-MFR documents must carry the addressees printed on the source");
  }
  return problems;
}
